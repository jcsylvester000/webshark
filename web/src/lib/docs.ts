/** Generates Markdown documentation from an environment canvas (inventory, links, findings). */
import { kindOf, nodeTarget } from "./nodes";
import type { Canvas } from "./types";

const esc = (s: unknown) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

export function canvasToMarkdown(name: string, description: string, canvas: Canvas): string {
  const byId = Object.fromEntries(canvas.nodes.map((n) => [n.id, n]));
  const lines: string[] = [`# ${name}`, "", description || "_No description._", "", `_Generated by Slyshark on ${new Date().toISOString().slice(0, 10)}_`, ""];
  const assets = canvas.nodes.filter((n) => !["note", "attacker", "vulnerability"].includes(n.data.kind));
  lines.push("## Inventory", "", "| Component | Type | Host / URL | Zone | OS | Ports | Status |", "|---|---|---|---|---|---|---|");
  for (const n of assets) {
    const d = n.data;
    const status = d.ping ? (d.ping.ok ? `up (${d.ping.avg_ms ?? "?"} ms)` : "unreachable") : "not tested";
    lines.push(`| ${esc(d.label)} | ${esc(kindOf(d.kind).label)} | ${esc(d.url || d.host || "-")} | ${esc(d.zone || "-")} | ${esc(d.os || "-")} | ${esc(d.ports || kindOf(d.kind).ports || "-")} | ${status} |`);
  }
  lines.push("", "## Connections", "", "| From | To | Label | Protocol | Port | Encrypted |", "|---|---|---|---|---|---|");
  for (const e of canvas.edges.filter((e) => !e.data?.attack)) {
    lines.push(`| ${esc(byId[e.source]?.data.label)} | ${esc(byId[e.target]?.data.label)} | ${esc(e.data?.label || "-")} | ${esc(e.data?.protocol || "-")} | ${esc(e.data?.port || "-")} | ${e.data?.encrypted ? "yes" : "no"} |`);
  }
  const scanned = canvas.nodes.filter((n) => n.data.scan || n.data.audit);
  if (scanned.length) {
    lines.push("", "## Test Results", "");
    for (const n of scanned) {
      const d = n.data;
      lines.push(`### ${d.label} (${nodeTarget(d) ?? "-"})`);
      if (d.scan) {
        lines.push(`- Port scan ${d.scan.at.slice(0, 16).replace("T", " ")} → ${d.scan.address}: ${d.scan.open.length ? d.scan.open.map((p) => `${p.port}/${p.service}`).join(", ") : "no open ports found"}`);
        for (const p of d.scan.open.filter((p) => p.note)) lines.push(`  - ⚠ ${p.port}: ${p.note}`);
      }
      if (d.audit) lines.push(`- Security header audit: score ${d.audit.score}/100, ${d.audit.issues} issue(s)`);
      lines.push("");
    }
  }
  const threats = canvas.nodes.filter((n) => n.data.kind === "attacker" || n.data.kind === "vulnerability");
  const attackEdges = canvas.edges.filter((e) => e.data?.attack);
  if (threats.length || attackEdges.length) {
    lines.push("## Security Scenarios", "");
    for (const t of threats) lines.push(`- **${esc(t.data.label)}** (${kindOf(t.data.kind).label})${t.data.notes ? `: ${t.data.notes}` : ""}`);
    if (attackEdges.length) {
      lines.push("", "**Attack path:**", "");
      for (const e of attackEdges) lines.push(`1. ${byId[e.source]?.data.label} → ${byId[e.target]?.data.label}${e.data?.label ? `: ${e.data.label}` : ""}`);
    }
    lines.push("");
  }
  const notes = canvas.nodes.filter((n) => n.data.notes && !["attacker", "vulnerability"].includes(n.data.kind));
  if (notes.length) {
    lines.push("## Notes", "");
    for (const n of notes) lines.push(`- **${esc(n.data.label)}:** ${n.data.notes}`);
  }
  return lines.join("\n") + "\n";
}

export function download(filename: string, content: string, type = "text/markdown") {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
